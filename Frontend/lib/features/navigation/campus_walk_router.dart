import 'dart:convert';
import 'dart:math' as math;

import 'package:flutter/services.dart';
import 'package:latlong2/latlong.dart';

/// Routes along the REAL OpenStreetMap footpaths/roads (the white lines on the
/// map). Data comes from `assets/maps/campus_paths.json`
/// (generated by `Backend/tools/fetch_campus_paths.py`), so it works offline.
///
/// Start/end are snapped to the nearest point on the nearest path, then
/// Dijkstra walks the path network and returns the exact polyline.
class CampusWalkRouter {
  CampusWalkRouter._();

  static const String assetPath = 'assets/maps/campus_paths.json';

  static _Graph? _graph;

  static Future<void> ensureLoaded() async {
    if (_graph != null) return;
    final raw = await rootBundle.loadString(assetPath);
    final json = jsonDecode(raw) as Map<String, dynamic>;
    _graph = _Graph.fromJson(json);
  }

  /// Walking polyline between two coordinates, or null if no path exists.
  static Future<WalkRoute?> route(LatLng from, LatLng to) async {
    await ensureLoaded();
    return _graph!.route(from, to);
  }
}

class WalkRoute {
  const WalkRoute({required this.points, required this.meters});
  final List<LatLng> points;
  final double meters;
}

class _Edge {
  _Edge(this.to, this.w);
  final int to;
  final double w;
}

class _Graph {
  _Graph(this.nodes, this.adj, this.segments);

  final List<LatLng> nodes;
  final List<List<_Edge>> adj;
  // Segments for snapping: [nodeA, nodeB]
  final List<(int, int)> segments;

  static const _dist = Distance();

  factory _Graph.fromJson(Map<String, dynamic> json) {
    final nodes = <LatLng>[];
    final adj = <List<_Edge>>[];
    final segments = <(int, int)>[];
    // Merge identical coordinates so ways that share a point connect.
    final index = <String, int>{};

    int nodeFor(double lat, double lng) {
      final key = '${lat.toStringAsFixed(6)},${lng.toStringAsFixed(6)}';
      return index.putIfAbsent(key, () {
        nodes.add(LatLng(lat, lng));
        adj.add(<_Edge>[]);
        return nodes.length - 1;
      });
    }

    final ways = (json['ways'] as List).cast<Map<String, dynamic>>();
    for (final way in ways) {
      final pts = (way['p'] as List).cast<List>();
      int? prev;
      for (final p in pts) {
        final cur = nodeFor((p[0] as num).toDouble(), (p[1] as num).toDouble());
        if (prev != null && prev != cur) {
          final w = _dist(nodes[prev], nodes[cur]);
          adj[prev].add(_Edge(cur, w));
          adj[cur].add(_Edge(prev, w));
          segments.add((prev, cur));
        }
        prev = cur;
      }
    }
    return _Graph(nodes, adj, _mainComponentSegments(adj, segments));
  }

  /// Keep only segments of the largest connected network (ignore stray bits).
  static List<(int, int)> _mainComponentSegments(
    List<List<_Edge>> adj,
    List<(int, int)> segments,
  ) {
    final comp = List<int>.filled(adj.length, -1);
    final sizes = <int>[];
    for (var s = 0; s < adj.length; s++) {
      if (comp[s] != -1) continue;
      final id = sizes.length;
      var count = 0;
      final stack = <int>[s];
      while (stack.isNotEmpty) {
        final u = stack.removeLast();
        if (comp[u] != -1) continue;
        comp[u] = id;
        count++;
        for (final e in adj[u]) {
          if (comp[e.to] == -1) stack.add(e.to);
        }
      }
      sizes.add(count);
    }
    if (sizes.isEmpty) return segments;
    var main = 0;
    for (var i = 1; i < sizes.length; i++) {
      if (sizes[i] > sizes[main]) main = i;
    }
    return segments.where((s) => comp[s.$1] == main).toList(growable: false);
  }

  /// Nearest point on any segment → (segment index, point, t).
  ({int seg, LatLng point, double d}) _snap(LatLng p) {
    var bestD = double.infinity;
    var bestSeg = -1;
    LatLng bestPt = p;
    // Local equirectangular projection (metres) — fine at campus scale.
    final cosLat = math.cos(p.latitude * math.pi / 180);
    double mx(double lng) => (lng - p.longitude) * 111320 * cosLat;
    double my(double lat) => (lat - p.latitude) * 110540;

    for (var i = 0; i < segments.length; i++) {
      final a = nodes[segments[i].$1];
      final b = nodes[segments[i].$2];
      final ax = mx(a.longitude), ay = my(a.latitude);
      final bx = mx(b.longitude), by = my(b.latitude);
      final dx = bx - ax, dy = by - ay;
      final len2 = dx * dx + dy * dy;
      var t = len2 == 0 ? 0.0 : ((-ax) * dx + (-ay) * dy) / len2;
      t = t.clamp(0.0, 1.0);
      final px = ax + t * dx, py = ay + t * dy;
      final d = math.sqrt(px * px + py * py);
      if (d < bestD) {
        bestD = d;
        bestSeg = i;
        bestPt = LatLng(
          a.latitude + (b.latitude - a.latitude) * t,
          a.longitude + (b.longitude - a.longitude) * t,
        );
      }
    }
    return (seg: bestSeg, point: bestPt, d: bestD);
  }

  WalkRoute? route(LatLng from, LatLng to) {
    if (segments.isEmpty) return null;
    final s = _snap(from);
    final e = _snap(to);
    if (s.seg < 0 || e.seg < 0) return null;

    // Virtual nodes appended after the real ones.
    final n = nodes.length;
    final startId = n;
    final endId = n + 1;
    final allNodes = [...nodes, s.point, e.point];

    // Extra edges (virtual → segment endpoints) kept sparse in a map.
    final extra = <int, List<_Edge>>{};
    void link(int v, int node, LatLng vp) {
      final w = _dist(vp, nodes[node]);
      extra.putIfAbsent(v, () => []).add(_Edge(node, w));
      extra.putIfAbsent(node, () => []).add(_Edge(v, w));
    }

    final sa = segments[s.seg];
    link(startId, sa.$1, s.point);
    link(startId, sa.$2, s.point);
    final ea = segments[e.seg];
    link(endId, ea.$1, e.point);
    link(endId, ea.$2, e.point);

    // Same segment: walk directly between the two snapped points.
    if (s.seg == e.seg) {
      final w = _dist(s.point, e.point);
      extra.putIfAbsent(startId, () => []).add(_Edge(endId, w));
      extra.putIfAbsent(endId, () => []).add(_Edge(startId, w));
    }

    Iterable<_Edge> neighbors(int u) sync* {
      if (u < n) yield* adj[u];
      final x = extra[u];
      if (x != null) yield* x;
    }

    final total = n + 2;
    final dist = List<double>.filled(total, double.infinity);
    final prev = List<int>.filled(total, -1);
    final done = List<bool>.filled(total, false);
    dist[startId] = 0;

    // Simple binary-heap-free Dijkstra using a sorted frontier (graph is small).
    final frontier = <int>{startId};
    while (frontier.isNotEmpty) {
      var u = -1;
      var best = double.infinity;
      for (final f in frontier) {
        if (dist[f] < best) {
          best = dist[f];
          u = f;
        }
      }
      if (u == -1) break;
      frontier.remove(u);
      if (done[u]) continue;
      done[u] = true;
      if (u == endId) break;
      for (final ed in neighbors(u)) {
        final alt = dist[u] + ed.w;
        if (alt < dist[ed.to]) {
          dist[ed.to] = alt;
          prev[ed.to] = u;
          frontier.add(ed.to);
        }
      }
    }

    if (dist[endId] == double.infinity) return null;

    final ids = <int>[];
    for (var c = endId; c != -1; c = prev[c]) {
      ids.add(c);
    }
    final pts = ids.reversed.map((i) => allNodes[i]).toList();

    // Include the true building positions at both ends (short connector).
    return WalkRoute(
      points: [from, ...pts, to],
      meters: dist[endId] + s.d + e.d,
    );
  }
}
